"""Example lesson catalog, one set of units per seeded language (F5 S1, S8).

This is example content for local development, not a curriculum: it exists so the lessons screens
show something real and so the deterministic grading has something to grade. Content is authored
in code (not generated by the model) because `desing.md` §13 puts lesson generation after the base
phase and because a deterministic catalog is what makes the grading testable (ADR-017).

Every answer list is ordered: the first accepted answer is the one the API shows when the student
misses the exercise.
"""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class ExerciseSeed:
    """One exercise of the example catalog.

    `kind` is `writing` (the student produces the phrase) or `choice` (the student picks one of
    `options`). A choice exercise must have exactly one accepted answer and that answer must be one
    of its options: the deterministic grading compares the chosen text with the accepted ones, so a
    correct option missing from `answers` could never be right (ADR-021).
    """

    prompt: str
    answers: tuple[str, ...]
    explanation: str
    kind: str = "writing"
    options: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class LessonSeed:
    title: str
    difficulty: str
    estimated_minutes: int
    intro: str
    exercises: tuple[ExerciseSeed, ...]


@dataclass(frozen=True, slots=True)
class TermSeed:
    term: str
    translation: str
    note: str | None = None


@dataclass(frozen=True, slots=True)
class UnitSeed:
    kind: str
    title: str
    description: str
    lessons: tuple[LessonSeed, ...]


